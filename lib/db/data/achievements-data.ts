// Helper function to get achievement by ID
export function getAchievementById(id: number): Achievement | undefined {
  return achievements.find((achievement) => achievement.id === id)
}

// Helper function to get achievements by category
export function getAchievementsByCategory(category: string): Achievement[] {
  return achievements.filter((achievement) => achievement.category === category)
}

// Helper function to get achievements by rarity
export function getAchievementsByRarity(rarity: string): Achievement[] {
  return achievements.filter((achievement) => achievement.rarity === rarity)
}
