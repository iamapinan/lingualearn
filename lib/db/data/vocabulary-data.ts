/**
 * Returns a random vocabulary item from the englishThaiVocabulary array
 */
export function getRandomVocabulary(): VocabularyItem {
  const randomIndex = Math.floor(Math.random() * vocabulary.length)
  return vocabulary[randomIndex]
}

/**
 * Returns a filtered list of vocabulary items based on category
 */
export function getVocabularyByCategory(category: string): VocabularyItem[] {
  return vocabulary.filter((item) => item.category === category)
}

/**
 * Returns a filtered list of vocabulary items based on difficulty
 */
export function getVocabularyByDifficulty(difficulty: number): VocabularyItem[] {
  return vocabulary.filter((item) => item.difficulty === difficulty)
}

/**
 * Returns a random set of vocabulary items with the specified count
 */
export function getRandomVocabularySet(count: number): VocabularyItem[] {
  const shuffled = [...vocabulary].sort(() => 0.5 - Math.random())
  return shuffled.slice(0, count)
}
